from __future__ import annotations

from pydantic import Field
from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, SdkBaseModel
from .enums.status11 import Status11OrStr
from .links7 import Links7, Links7Dict
from .localized_information4 import LocalizedInformation4, LocalizedInformation4Dict
from .store_location1 import StoreLocation1, StoreLocation1Dict
from .store_split_configuration1 import StoreSplitConfiguration1, StoreSplitConfiguration1Dict
from .sub_merchant_data1 import SubMerchantData1, SubMerchantData1Dict


class Store(SdkBaseModel):
    links: Optional[Links7] = Field(default=UNSET, alias="_links")
    """Reference to resources connected with the store."""

    address: Optional[StoreLocation1] = UNSET
    """The address of the store."""

    business_line_ids: Optional[list[str]] = Field(default=UNSET, alias="businessLineIds")
    """The unique identifiers of the `business lines
    <https://docs.adyen.com/api-explorer/#/legalentity/latest/post/businesslines__resParam_id>`__ that the store is
    associated with.
     If not specified, the business line of the merchant account is used. Required when there are multiple business
        lines under the merchant account."""

    description: Optional[str] = UNSET
    """The description of the store."""

    external_reference_id: Optional[str] = Field(default=UNSET, alias="externalReferenceId")
    """The unique identifier of the store, used by certain payment methods and tax authorities.

    Required for CNPJ in Brazil, in the format 00.000.000/0000-00 separated by dots, slashes, hyphens, or without
    separators.

    Optional for SIRET in France, up to 14 digits.

    Optional for Zip in Australia, up to 50 digits."""

    id: Optional[str] = UNSET
    """The unique identifier of the store. This value is generated by Adyen."""

    localized_information: Optional[LocalizedInformation4] = Field(default=UNSET, alias="localizedInformation")
    """The localized information of the store."""

    merchant_id: Optional[str] = Field(default=UNSET, alias="merchantId")
    """The unique identifier of the merchant account that the store belongs to."""

    phone_number: Optional[str] = Field(default=UNSET, alias="phoneNumber")
    """The phone number of the store, including '+' and country code in the `E.164
    <https://en.wikipedia.org/wiki/E.164>`__ format. If passed in a different format, we convert and validate the phone
    number against E.164."""

    reference: Optional[str] = UNSET
    """A reference to recognize the store by. Also known as the store code.
     Allowed characters: lowercase and uppercase letters without diacritics, numbers 0 through 9, hyphen (-), and
        underscore (_)"""

    shopper_statement: Optional[str] = Field(default=UNSET, alias="shopperStatement")
    """The store name shown on the shopper's bank or credit card statement and on the shopper receipt."""

    split_configuration: Optional[StoreSplitConfiguration1] = Field(default=UNSET, alias="splitConfiguration")
    """Rules for Adyen for Platforms merchants to split the transaction amount and fees."""

    status: Optional[Status11OrStr] = UNSET
    """The status of the store. Possible values are:

    - **active**. This value is assigned automatically when a store is created.
    - **inactive**. The terminals under the store are blocked from accepting new transactions, but capturing outstanding
        transactions is still possible.
    - **closed**. This status is irreversible. The terminals under the store are reassigned to the merchant
        inventory."""

    sub_merchant_data: Optional[SubMerchantData1] = Field(default=UNSET, alias="subMerchantData")
    """The sub-merchant data relevant for registered payment facilitators transacting on standalone terminals."""


class StoreDict(TypedDict):
    links: NotRequired[Links7Dict]
    address: NotRequired[StoreLocation1Dict]
    business_line_ids: NotRequired[list[str]]
    description: NotRequired[str]
    external_reference_id: NotRequired[str]
    id: NotRequired[str]
    localized_information: NotRequired[LocalizedInformation4Dict]
    merchant_id: NotRequired[str]
    phone_number: NotRequired[str]
    reference: NotRequired[str]
    shopper_statement: NotRequired[str]
    split_configuration: NotRequired[StoreSplitConfiguration1Dict]
    status: NotRequired[Status11OrStr]
    sub_merchant_data: NotRequired[SubMerchantData1Dict]
