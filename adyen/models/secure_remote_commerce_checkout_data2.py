from __future__ import annotations

from pydantic import Field
from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, SdkBaseModel
from .enums.scheme import SchemeOrStr


class SecureRemoteCommerceCheckoutData2(SdkBaseModel):
    """Checkout data for a Secure Remote Commerce payment."""

    checkout_payload: Optional[str] = Field(default=UNSET, alias="checkoutPayload")
    """The Secure Remote Commerce checkout payload to process the payment with."""

    correlation_id: Optional[str] = Field(default=UNSET, alias="correlationId")
    """This is the unique identifier generated by SRC system to track and link SRC messages. Available within the
    present checkout session (e.g. received in an earlier API response during the present session)."""

    cvc: Optional[str] = UNSET
    """The `card verification code
    <https://docs.adyen.com/get-started-with-adyen/payment-glossary/#card-security-code-cvc-cvv-cid>`__."""

    digital_card_id: Optional[str] = Field(default=UNSET, alias="digitalCardId")
    """A unique identifier that represents the token associated with a card enrolled. Required for scheme 'mc'."""

    scheme: Optional[SchemeOrStr] = UNSET
    """The Secure Remote Commerce scheme."""

    token_reference: Optional[str] = Field(default=UNSET, alias="tokenReference")
    """A unique identifier that represents the token associated with a card enrolled. Required for scheme 'visa'."""


class SecureRemoteCommerceCheckoutData2Dict(TypedDict):
    checkout_payload: NotRequired[str]
    correlation_id: NotRequired[str]
    cvc: NotRequired[str]
    digital_card_id: NotRequired[str]
    scheme: NotRequired[SchemeOrStr]
    token_reference: NotRequired[str]
